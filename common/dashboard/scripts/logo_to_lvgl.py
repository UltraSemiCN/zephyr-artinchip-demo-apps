"""Convert a logo to an LVGL RGB565A8 const image (requires Pillow)."""

import argparse
from pathlib import Path
import re

from PIL import Image


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--symbol", required=True)
    parser.add_argument("--height", type=int, default=48)
    parser.add_argument("--max-width", type=int, default=204)
    parser.add_argument("--alpha-threshold", type=int, default=1,
                        help="minimum alpha used to find visible bounds (1..255)")
    args = parser.parse_args()
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", args.symbol):
        parser.error("symbol must be a C identifier")
    if args.height <= 0 or args.max_width <= 0:
        parser.error("dimensions must be positive")

    if not 1 <= args.alpha_threshold <= 255:
        parser.error("alpha threshold must be between 1 and 255")

    with Image.open(args.source) as source:
        logo = source.convert("RGBA")
    bounds = logo.getchannel("A").point(
        lambda value: 255 if value >= args.alpha_threshold else 0).getbbox()
    if bounds is None:
        parser.error("logo is fully transparent")
    logo = logo.crop(bounds)
    width = max(1, round(logo.width * args.height / logo.height))
    if width > args.max_width:
        parser.error(f"logo would be {width}px wide; reduce the height of BOTH logos")
    logo = logo.resize((width, args.height), Image.Resampling.LANCZOS)
    colors = bytearray()
    alpha = bytearray()
    for red, green, blue, opacity in logo.getdata():
        rgb565 = ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)
        colors.extend(rgb565.to_bytes(2, "little"))
        alpha.append(opacity)
    data = colors + alpha
    rows = ["\t" + ", ".join(f"0x{x:02x}" for x in data[i:i + 16]) + ","
            for i in range(0, len(data), 16)]
    output = f'''/* Generated by logo_to_lvgl.py; logo rights remain with their owners. */
#include <lvgl.h>

LV_ATTRIBUTE_MEM_ALIGN static const uint8_t {args.symbol}_data[] = {{
{chr(10).join(rows)}
}};

const lv_image_dsc_t {args.symbol} = {{
\t.header.magic = LV_IMAGE_HEADER_MAGIC,
\t.header.cf = LV_COLOR_FORMAT_RGB565A8,
\t.header.w = {width},
\t.header.h = {args.height},
\t.header.stride = {width * 2},
\t.data_size = sizeof({args.symbol}_data),
\t.data = {args.symbol}_data,
}};
'''
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output)
    print(f"{args.output}: {width}x{args.height}, {len(data)} pixel bytes")


if __name__ == "__main__":
    main()
