"""Bake the existing RGB565A8 logos and websites into a small boot framebuffer.

Requires Pillow and a supplied TrueType font. Output is a source asset, not
an extra build dependency. Logo rights remain with their respective owners.
"""
import argparse
from pathlib import Path
import re
from PIL import Image, ImageDraw, ImageFont


def generate(font_path):
    root = Path(__file__).resolve().parent
    canvas = Image.new("RGB", (480, 96), "black")
    for index, (name, website) in enumerate([
        ("artinchip", "www.artinchip.com"), ("ultrasemi", "www.ultrasemi.com")
    ]):
        source = (root.parent / "dashboard/src/assets" / f"{name}_logo.c").read_text()
        width = int(re.search(r"\.header.w = (\d+)", source)[1])
        height = int(re.search(r"\.header.h = (\d+)", source)[1])
        data = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", source))
        count = width * height
        assert len(data) == count * 3
        rgba = []
        for i in range(count):
            pixel = int.from_bytes(data[2*i:2*i+2], "little")
            rgba.append(((pixel >> 11) * 255 // 31,
                         ((pixel >> 5) & 63) * 255 // 63,
                         (pixel & 31) * 255 // 31, data[count*2+i]))
        logo = Image.new("RGBA", (width, height))
        logo.putdata(rgba)
        center = 120 + index * 240
        canvas.paste(logo, (center - width // 2, 8), logo)
        draw = ImageDraw.Draw(canvas)
        draw.text((center, 70), website, anchor="mm", fill="#e0e6ed",
                  font=ImageFont.truetype(str(font_path), 18))
    values = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
              for r, g, b in canvas.getdata()]
    lines = ["\t" + ", ".join(f"0x{p:04x}" for p in values[i:i+12]) + ","
             for i in range(0, len(values), 12)]
    (root / "image.c").write_text(
        "/* SPDX-License-Identifier: Apache-2.0 */\n"
        "/* Generated by generate.py; logo rights remain with their owners. */\n"
        "#include <stdint.h>\n\n"
        "const uint16_t dashboard_boot_pixels[480 * 96] = {\n" +
        "\n".join(lines) + "\n};\n")
    canvas.save(root / "preview.png")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, required=True)
    generate(parser.parse_args().font)
